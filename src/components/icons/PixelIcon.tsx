export type PixelIconName = keyof typeof SPRITES;

const GRID = 16;

function spriteToPath(rows: readonly string[]): string {
  const width = Math.max(...rows.map((row) => row.length));
  const offsetX = Math.floor((GRID - width) / 2);
  const offsetY = Math.floor((GRID - rows.length) / 2);
  let path = "";

  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== "#") {
        x += 1;
        continue;
      }
      let run = 1;
      while (row[x + run] === "#") run += 1;
      path += `M${x + offsetX} ${y + offsetY}h${run}v1h-${run}z`;
      x += run;
    }
  });

  return path;
}

const PATHS = Object.fromEntries(
  Object.entries(SPRITES).map(([name, rows]) => [name, spriteToPath(rows)]),
) as Record<PixelIconName, string>;

interface PixelIconProps {
  name: PixelIconName;
  className?: string;
  /** Isi hanya bila ikon berdiri sendiri tanpa teks di sebelahnya. */
  title?: string;
}

export default function PixelIcon({ name, className, title }: PixelIconProps) {
  return (
    <svg
      className={className ? `px-icon ${className}` : "px-icon"}
      viewBox={`0 0 ${GRID} ${GRID}`}
      shapeRendering="crispEdges"
      fill="currentColor"
      role={title ? "img" : undefined}
      aria-hidden={title ? undefined : true}
      focusable="false"
    >
      {title ? <title>{title}</title> : null}
      <path d={PATHS[name]} />
    </svg>
  );
}
